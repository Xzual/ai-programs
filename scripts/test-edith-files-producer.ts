for(const denied of ['.edith-build','backup-reference','.restore-review','local-state','.cursor','venv','vendor','cache','recovery','vault']) {
  fs.mkdirSync(path.join(root,denied));fs.writeFileSync(path.join(root,denied,'hidden.md'),'must not scan');
}
fs.linkSync(path.join(temp,'outside.md'),path.join(root,'outside-hardlink.md'));
// A directory junction on Windows needs no symlink privilege and exercises reparse denial.
fs.symlinkSync(temp,path.join(root,'escape'),process.platform === 'win32' ? 'junction' : 'dir');
const service = new FileService(() => [{id:'workspace',path:root,excluded:[path.join(root,'excluded')]}]);
const app = express(); app.use(express.json()); app.use(createOwnerSessionRouter()); app.use(createFilesRouter(service));
let providerCalls=0,providerAvailable=true,emptySummary=false;
app.get('/api/tags',(_req,res)=>res.json({models:providerAvailable?[{name:'fixture-summary-model'}]:[]}));
app.post('/api/chat',(req,res)=>{
  providerCalls++;assert.equal(req.body.messages[1].content,content,'Real adapter receives selected file content');
  res.set('content-type','application/x-ndjson');
  res.end(JSON.stringify({message:{content:emptySummary?'':'Fixture summary of actual document.'},done:true})+'\n');
});
const server = createServer(app);
process.env.EDITH_OWNER_TOKEN = 'isolated-files-owner';
try {
  const result = service.search();
  assert.equal(result.files.some(file => /\.env|credentials|hidden|outside|escape/.test(file.relativePath)),false);
  const file = result.files.find(file => file.name === 'çalışma.md')!;
  assert.ok(file); assert.equal(path.isAbsolute(file.relativePath),false);
  assert.equal(service.read(file.id).text,content);
  assert.equal(service.read(file.id).bytes,Buffer.byteLength(content));
  assert.throws(() => service.read('../outside.md'),/FILE_ID_INVALID/);
  assert.throws(() => service.read('a'.repeat(64)),/FILE_NOT_FOUND/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'large.txt')!.id),/FILE_READ_LIMIT/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'binary.txt')!.id),/FILE_TEXT_UNSUPPORTED/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'ordinary.json')!.id),/FILE_SECRET_CONTENT_DENIED/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'ordinary-notes.md')!.id),/FILE_SECRET_CONTENT_DENIED/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'ordinary-config.json')!.id),/FILE_SECRET_CONTENT_DENIED/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'ordinary-notes.yaml')!.id),/FILE_SECRET_CONTENT_DENIED/);
  assert.throws(() => service.read(result.files.find(file => file.name === 'ordinary-notes.txt')!.id),/FILE_SECRET_CONTENT_DENIED/);
  assert.equal(service.search('',1).truncated,true);
  assert.throws(() => service.search('',101),/FILES_QUERY_INVALID/);
  await new Promise<void>(resolve => server.listen(0,'127.0.0.1',resolve));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  assert.equal((await fetch(origin+'/api/files/search',{headers:{origin}})).status,401);
  const login = await fetch(origin+'/api/security/session',{method:'POST',headers:{origin,authorization:'Bearer isolated-files-owner'}});
  assert.equal(login.status,201);
  const cookie = login.headers.get('set-cookie')!.split(';')[0];
  const ownerBody=await login.json() as any;
  const headers = {origin,cookie};
  const found = await (await fetch(origin+'/api/files/search?q='+encodeURIComponent('çalışma'),{headers})).json() as any;
  assert.equal(found.files.length,1);
  const read = await (await fetch(origin+`/api/files/${found.files[0].id}/content`,{headers})).json() as any;
  assert.equal(read.text,content);
  assert.equal(JSON.stringify(found).includes(root),false);
  assert.equal((await fetch(origin+'/api/files/search?root='+encodeURIComponent(temp),{headers})).status,400);
  assert.equal((await fetch(origin+'/api/files/search',{headers:{cookie,origin:'https://foreign.invalid'}})).status,403);
  process.env.OLLAMA_HOST=origin;
  const mutationHeaders={...headers,'content-type':'application/json','x-edith-csrf-token':ownerBody.session.csrfToken};
  const summaryUrl=origin+`/api/files/${file.id}/summarize`;
  const summarized=await fetch(summaryUrl,{method:'POST',headers:mutationHeaders,body:'{}'});assert.equal(summarized.status,200);
  const summary=await summarized.json() as any;assert.equal(summary.completed,true);assert.equal(summary.summary,'Fixture summary of actual document.');assert.equal(summary.provider,'ollama');assert.equal(providerCalls,1);
  assert.equal((await fetch(summaryUrl,{method:'POST',headers,body:'{}'})).status,403);
  assert.equal((await fetch(summaryUrl,{method:'POST',headers:mutationHeaders,body:JSON.stringify({provider:'gemini'})})).status,403);
  providerAvailable=false;assert.equal((await fetch(summaryUrl,{method:'POST',headers:mutationHeaders,body:'{}'})).status,503);assert.equal(providerCalls,1,'Unavailable provider must not fabricate a summary');providerAvailable=true;
  emptySummary=true;assert.equal((await fetch(summaryUrl,{method:'POST',headers:mutationHeaders,body:'{}'})).status,502);emptySummary=false;
  assert.equal((await fetch(origin+`/api/files/${file.id}/open`,{method:'POST',headers:mutationHeaders,body:'{}'})).status,501);
  const emptySend=await fetch(origin+`/api/files/${file.id}/send`,{method:'POST',headers:mutationHeaders,body:'{}'});
  assert.equal(emptySend.status,400);assert.equal((await emptySend.json() as any).errorCode,'FILES_ACTION_INVALID');
  fs.writeFileSync(path.join(root,'renamed-source.md'),'rename fixture');
  const renamedFile=service.search('renamed-source').files[0];assert.ok(renamedFile);
  fs.renameSync(path.join(root,'renamed-source.md'),path.join(root,'renamed-destination.md'));
  assert.throws(()=>service.read(renamedFile.id),(error:any)=>error.code==='FILE_NOT_FOUND' && error.status===404);
  const renameResponse=await fetch(origin+`/api/files/${renamedFile.id}/content`,{headers});assert.equal(renameResponse.status,404);assert.equal((await renameResponse.json() as any).errorCode,'FILE_NOT_FOUND');
  fs.mkdirSync(path.join(temp,'disappearing-root'));fs.writeFileSync(path.join(temp,'disappearing-root','note.md'),'own temporary root');
  const disappearing=new FileService(()=>[{id:'workspace',path:path.join(temp,'disappearing-root')}]);const disappearedId=disappearing.search().files[0].id;
  fs.unlinkSync(path.join(temp,'disappearing-root','note.md'));fs.rmdirSync(path.join(temp,'disappearing-root'));
  assert.throws(()=>disappearing.read(disappearedId),(error:any)=>error.code==='FILE_NOT_FOUND' && error.status===404);
  fs.unlinkSync(path.join(root,'çalışma.md'));
  assert.throws(()=>service.read(file.id),(error:any)=>error.code==='FILE_NOT_FOUND' && error.status===404);
  const deletionResponse=await fetch(origin+`/api/files/${file.id}/content`,{headers});assert.equal(deletionResponse.status,404);assert.equal((await deletionResponse.json() as any).errorCode,'FILE_NOT_FOUND');
  fs.symlinkSync(path.join(temp,'outside.md'),path.join(root,'çalışma.md'),'file');
  assert.throws(() => service.read(file.id),/FILE_SCOPE_DENIED/,'A discovered file replaced by a link must be denied');
  const substitutionResponse=await fetch(origin+`/api/files/${file.id}/content`,{headers});assert.equal(substitutionResponse.status,403);assert.equal((await substitutionResponse.json() as any).errorCode,'FILE_SCOPE_DENIED');
  console.log(JSON.stringify({success:true,realUnicodeBytes:true,opaqueIds:true,boundedSearch:true,outsideReparseSecretDenied:true,normalJsonEnvYamlBearerCanariesDenied:true,ownerOriginEnforced:true,realOllamaHttpSummary:true,noMockSummary:true,nativeOpenOutboundSendUnavailable:true,staleDeletedRenamedRootMissing404:true,symlinkSubstitutionStill403:true}));
} finally {
  if (server.listening) await new Promise<void>(resolve => server.close(() => resolve()));
  // Remove junction first so cleanup never traverses its outside target.
  fs.unlinkSync(path.join(root,'escape'));
  fs.rmSync(temp,{recursive:true,force:true});
}
