const temp = fs.mkdtempSync(path.join(os.tmpdir(),'edith-files-'));
const root = path.join(temp,'workspace');
fs.mkdirSync(root);
const content = 'Gerçek içerik: İstanbul — çalışma 🧪\n';
fs.writeFileSync(path.join(root,'çalışma.md'),content);
fs.writeFileSync(path.join(root,'.env'),'DO_NOT_READ=fixture');
fs.writeFileSync(path.join(root,'credentials.json'),'private fixture');
fs.writeFileSync(path.join(temp,'outside.md'),'outside fixture');
fs.mkdirSync(path.join(root,'runtime'));
fs.writeFileSync(path.join(root,'runtime','hidden.md'),'hidden fixture');
fs.mkdirSync(path.join(root,'backup'));
fs.writeFileSync(path.join(root,'backup','hidden.md'),'hidden fixture');
fs.mkdirSync(path.join(root,'excluded'));
fs.writeFileSync(path.join(root,'excluded','hidden.md'),'excluded fixture');
fs.writeFileSync(path.join(root,'large.txt'),Buffer.alloc(262145,65));
fs.writeFileSync(path.join(root,'binary.txt'),Buffer.from([0,255,1]));
fs.writeFileSync(path.join(root,'ordinary.json'),JSON.stringify({access_token:'fixture-must-not-leave'}));
fs.writeFileSync(path.join(root,'ordinary-notes.md'),'GEMINI_API_KEY=provider-canary-must-not-leave\n');
fs.writeFileSync(path.join(root,'ordinary-config.json'),JSON.stringify({apiKey:'provider-canary-must-not-leave'}));
