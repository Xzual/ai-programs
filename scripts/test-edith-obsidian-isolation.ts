import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'edith-vault-isolation-'));
const originalCwd = process.cwd();
const vault = path.join(root, 'Seçili Kasa EDİTH');
const legacyVault = path.join(root, 'legacy-untrusted');
const outside = path.join(root, 'outside');
process.env.EDITH_PERSISTENCE = 'json';
process.env.EDITH_OBSIDIAN_PROVIDER_APP_ROOT = originalCwd;
process.env.EDITH_KNOWLEDGE_GRAPH_AUTOSYNC = 'false';
process.env.EDITH_TEST_OBSIDIAN_SANDBOX_ROOT = vault;
process.env.OBSIDIAN_VAULT_PATH = legacyVault;
process.chdir(root);
let close: (() => void) | undefined;
try {
  fs.mkdirSync(path.join(vault, 'Projects'), { recursive: true });
  fs.mkdirSync(legacyVault);
  fs.mkdirSync(outside);
  fs.writeFileSync(path.join(vault, 'Projects', 'Doğrulanmış.md'), '# Doğrulanmış\n\n#seçili\n');
  fs.writeFileSync(path.join(legacyVault, 'Forbidden.md'), '# Legacy source must not be indexed\n');
  fs.writeFileSync(path.join(outside, 'outside.md'), '# Outside file\n');
  const { obsidianVaultService } = await import('../src/edith/obsidianVaultService');
  const { knowledgeGraphService } = await import('../src/edith/knowledgeGraphService');
  const { obsidianProviderConfigService } = await import('../src/edith/obsidianProviderService');
  const { getEdithPersistenceStore } = await import('../src/edith/persistence');
  const store = getEdithPersistenceStore();
  close = () => { obsidianVaultService.stopWatcher(); store.close?.(); };
  assert.equal(obsidianVaultService.reindex().success, true);
  const graph = knowledgeGraphService.snapshot();
  assert.ok(graph.nodes.some((node) => node.id === 'vault:obsidian'));
  assert.ok(graph.nodes.some((node) => node.title === 'Doğrulanmış'));
  assert.ok(graph.nodes.some((node) => node.title === 'Projects'));
  assert.ok(graph.relationships.some((edge) => edge.type === 'inside_folder'));
  assert.equal(graph.nodes.some((node) => node.title === 'Forbidden'), false);
  assert.equal(obsidianVaultService.getSettings().vaultPath, fs.realpathSync(vault));
  fs.symlinkSync(outside, path.join(vault, 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  const linked = obsidianVaultService.reindex();
  assert.equal(linked.success, false);
  assert.ok(linked.errors.some((error) => /LINK|Symbolic/.test(error)));
  assert.throws(() => obsidianVaultService.syncPath('linked/outside.md'), /LINK|Symbolic/);
  assert.equal((store.listObsidianNoteIndex?.() ?? []).some((record) => record.path.includes('outside')), false);
  assert.equal(fs.readFileSync(path.join(outside, 'outside.md'), 'utf8'), '# Outside file\n');
  const oldNote = graph.nodes.find((node) => node.title === 'Doğrulanmış')!;
  const nextVault = path.join(root, 'Yeni Seçili Kasa');
  fs.mkdirSync(path.join(nextVault, 'Research'), { recursive: true });
  fs.writeFileSync(path.join(nextVault, 'Research', 'Yeni.md'), '# Yeni\n');
  process.env.EDITH_TEST_OBSIDIAN_SANDBOX_ROOT = nextVault;
  const switched = knowledgeGraphService.snapshot();
  assert.equal(switched.nodes.some((node) => node.id === oldNote.id), false);
  assert.equal(switched.nodes.some((node) => node.title === 'Projects'), false);
  assert.equal(switched.relationships.some((edge) => edge.from === oldNote.id || edge.to === oldNote.id), false);
  assert.equal(knowledgeGraphService.findNode(oldNote.id), undefined);
  assert.equal(obsidianVaultService.reindex().success, true);
  assert.ok(knowledgeGraphService.snapshot().nodes.some((node) => node.title === 'Yeni'));
  assert.equal(knowledgeGraphService.findNode(oldNote.id), undefined);
  delete process.env.EDITH_TEST_OBSIDIAN_SANDBOX_ROOT;
  assert.equal(obsidianProviderConfigService.status().state, 'FIRST_RUN_REQUIRED');
  const unconfigured = knowledgeGraphService.snapshot();
  assert.equal(unconfigured.nodes.some((node) => node.source === 'obsidian'), false, 'No stale vault/note projection after provider is unavailable.');
  assert.equal(obsidianVaultService.status().connectionStatus, 'configuration_required');
  assert.equal(obsidianVaultService.status().indexedNotes, 0);
  assert.equal(obsidianVaultService.reindex().success, false);
  assert.equal(fs.readdirSync(legacyVault).length, 1);
  assert.equal(knowledgeGraphService.findNode('vault:obsidian'), undefined);
  console.log(JSON.stringify({ success: true, checks: ['selected_unicode_provider', 'legacy_path_ignored', 'real_vault_note_folder_edges', 'junction_traversal_rejected', 'provider_switch_no_old_note_or_edges_or_findNode', 'unconfigured_hides_stale_vault_and_notes'] }));
} finally {
  close?.();
  process.chdir(originalCwd);
  fs.rmSync(root, { recursive: true, force: true });
}
